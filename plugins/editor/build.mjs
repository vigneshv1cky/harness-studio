// Builds client.js, the file Harness loads: the bundled CodeMirror (vendor/codemirror.iife.js, which defines
// `CM`) followed by the editor's own client code (src/editor.client.js), wrapped in one function so `CM` stays
// private to this plugin. CodeMirror is set up only when an Editor tab first uses it: `CM` is a stand-in that
// runs the bundle on first access, so opening the app without editing a file costs no editor start-up.
// Run after changing either file:  node plugins/editor/build.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const vendor = readFileSync(new URL('vendor/codemirror.iife.js', here), 'utf8')
const source = readFileSync(new URL('src/editor.client.js', here), 'utf8')
const banner = '// Generated by build.mjs from src/editor.client.js and vendor/codemirror.iife.js (CodeMirror, MIT licence: vendor/LICENSE). Do not edit.\n'
const lazy = `var CM = (function () {
  var loaded
  function load() {
    if (loaded === undefined) loaded = (function () {
${vendor}
      return CM
    })()
    return loaded
  }
  return new Proxy({}, { get: function (_target, key) { return load()[key] } })
})();`
writeFileSync(new URL('client.js', here), `${banner};(function () {\n${lazy}\n${source}\n})();\n`)
console.log('wrote client.js')
